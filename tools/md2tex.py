#!/usr/bin/env python3
r"""Convert drafts/paper_en.md into sec/0_abstract.tex and sec/1_intro.tex, sec/2_related.tex, sec/3_method.tex.

Markdown conventions used by the draft:
  # n. Title            -> \section{Title}        \label{sec:<first word>}
  ## n.m Title          -> \subsection{Title}     \label{sec:n_m}
  - item                -> itemize
  **x** / *x*           -> \textbf{x} / \emph{x}
  $$ ... \tag{k} $$     -> equation with \label{eq:k}
  [[figure:name]] text  -> figure* with \input{fig/name}, caption = text, \label{fig:name}
  Eq.~(k), Sec.~n.m, Fig.~1[abc], Sec.~X -> \eqref / \ref
Usage: python3 tools/md2tex.py   (run from the repository root)
Preview without a TeX installation: tectonic -X compile main.tex (check main.log for 'Overfull \\hbox').
"""
import re
from pathlib import Path

SECTION_FILES = {"Introduction": "1_intro", "Related Work": "2_related", "Method": "3_method"}
HEADER = "% Generated by tools/md2tex.py from drafts/paper_en.md. Edit the draft, then re-run the script.\n"


def inline(t: str) -> str:
    t = re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", t)
    t = re.sub(r"(?<![\w\\$*])\*(?![\s*])(.+?)(?<![\s*])\*(?![\w*])", r"\\emph{\1}", t)
    t = re.sub(r"Eq\.~\((\d+)\)", r"Eq.~\\eqref{eq:\1}", t)
    t = re.sub(r"Sec\.~(\d+)\.(\d+)", r"Sec.~\\ref{sec:\1_\2}", t)
    t = re.sub(r"Fig\.~1([abc]?)", r"Fig.~\\ref{fig:overview}\1", t)
    t = t.replace("Sec.~X", "Sec.~\\ref{sec:experiments}")
    t = t.replace("–", "--").replace("&", "\\&").replace("%", "\\%")
    return t


def convert(md: str) -> str:
    out, in_list, in_eq, eq = [], False, False, []
    for line in md.split("\n"):
        if line.strip() == "$$":
            if not in_eq:
                in_eq, eq = True, []
            else:
                in_eq = False
                body = "\n".join(eq)
                m = re.search(r"\\tag\{(\d+)\}", body)
                body = re.sub(r"\s*\\tag\{\d+\}", "", body).strip()
                lab = f"\\label{{eq:{m.group(1)}}}" if m else ""
                out.append("\\begin{equation}" + lab + "\n" + body + "\n\\end{equation}")
            continue
        if in_eq:
            eq.append(line)
            continue
        if line.startswith("- "):
            if not in_list:
                out.append("\\begin{itemize}")
                in_list = True
            out.append("  \\item " + inline(line[2:]))
            continue
        if in_list:
            out.append("\\end{itemize}")
            in_list = False
        m = re.match(r"^\[\[figure:(\w+)\]\]\s*(.*)", line)
        if m:
            out.append("\\begin{figure*}[t]\n  \\centering\n  \\input{fig/" + m.group(1) + "}\n  \\caption{"
                       + inline(m.group(2)) + "}\n  \\label{fig:" + m.group(1) + "}\n\\end{figure*}")
            continue
        m = re.match(r"^# \d+\. (.*)", line)
        if m:
            out.append("\\section{" + m.group(1) + "}\n\\label{sec:" + m.group(1).lower().split()[0] + "}")
            continue
        m = re.match(r"^## (\d+)\.(\d+) (.*)", line)
        if m:
            out.append("\\subsection{" + m.group(3) + "}\n\\label{sec:" + m.group(1) + "_" + m.group(2) + "}")
            continue
        out.append(inline(line))
    if in_list:
        out.append("\\end{itemize}")
    return "\n".join(out)


def main():
    md = Path("drafts/paper_en.md").read_text()
    if "\n# Abstract\n" in md:
        abstract = md.split("\n# Abstract\n", 1)[1].split("\n# 1. Introduction", 1)[0].strip()
        Path("sec/0_abstract.tex").write_text(HEADER + "\\begin{abstract}\n" + inline(abstract) + "\n\\end{abstract}\n")
        print("wrote sec/0_abstract.tex")
    body = "# 1. Introduction" + md.split("\n# 1. Introduction", 1)[1]
    tex = convert(body)
    for part in re.split(r"(?=\\section\{)", tex):
        m = re.match(r"\\section\{([^}]*)\}", part)
        if m and m.group(1) in SECTION_FILES:
            Path(f"sec/{SECTION_FILES[m.group(1)]}.tex").write_text(HEADER + part.strip() + "\n")
            print("wrote", f"sec/{SECTION_FILES[m.group(1)]}.tex")


if __name__ == "__main__":
    main()
